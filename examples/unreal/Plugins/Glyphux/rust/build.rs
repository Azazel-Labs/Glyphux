//! Writes everything the plugin's C++ and shaders take from this crate, every build:
//!
//! * the Ferreal glue of the classes in `src/` (`UGlyphuxTextBlock`, `UGlyphuxTextComponent`),
//!   into `../Source/Glyphux/{Public,Private}/Ferreal/`;
//! * glyphux-gpu's compute kernels in HLSL (translated from their WGSL with naga), one `.usf`
//!   per kernel, and its text and color shading functions as `.ush` libraries for the
//!   materials, into `../Shaders/Private/Generated/`;
//! * the global shader classes of the kernels, whose parameters are the resources each
//!   kernel's HLSL declares, into the `GlyphuxShaders` module (`../Source/GlyphuxShaders`,
//!   which loads early enough to register global shaders);
//! * the sizes of the draw data (`src/records.rs`), into `../Source/Glyphux/Private/Generated/`.
//!
//! The generated files are committed (they ship with the plugin), and written only when they
//! change.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use glyphux_gpu::hlsl::{self, HlslKernel, HlslResource};

/// The sizes of the draw data, shared with the library.
#[path = "src/records.rs"]
mod records;
use glyphux_gpu::{AtlasFormat, Kernel};

/// The atlas format the plugin uses (glyphux-gpu's default, `AtlasConfig::default()`).
const FORMAT: AtlasFormat = AtlasFormat::Rgba8Unorm;

const BANNER: &str = "Generated by the Glyphux plugin's rust/build.rs from glyphux-gpu's WGSL\n// (translated with naga): do not edit. Edit the WGSL in Glyphux and build again.";

fn main() {
    ferreal_build::Module::new("Glyphux").output("../Source/Glyphux").run();
    println!("cargo:rerun-if-changed=../Shaders/Private/Generated");
    println!("cargo:rerun-if-changed=../Source/Glyphux/Private/Generated");
    println!("cargo:rerun-if-changed=../Source/GlyphuxShaders/Public/Generated");
    println!("cargo:rerun-if-changed=../Source/GlyphuxShaders/Private/Generated");

    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let shaders = manifest.join("../Shaders/Private/Generated");
    let records = manifest.join("../Source/Glyphux/Private/Generated");
    let shaders_public = manifest.join("../Source/GlyphuxShaders/Public/Generated");
    let shaders_private = manifest.join("../Source/GlyphuxShaders/Private/Generated");
    let mut shader_files: Vec<(PathBuf, String)> = Vec::new();
    let mut kernels = Vec::new();
    for kernel in Kernel::ALL {
        let k = hlsl::kernel(kernel, FORMAT).unwrap_or_else(|e| panic!("{kernel:?}: {e}"));
        shader_files.push((
            shaders.join(format!("{}.usf", kernel.entry_point())),
            format!(
                "// {BANNER}\n// The {} kernel ({kernel:?}).\n\n#include \"/Engine/Public/Platform.ush\"\n\n{}",
                kernel.entry_point(),
                k.source
            ),
        ));
        kernels.push((kernel, k));
    }
    shader_files.push((
        shaders.join("GlyphuxTextCore.ush"),
        library(
            "GLYPHUX_TEXT_CORE",
            "glyphux-gpu's text shading (text_core.wgsl)",
            &hlsl::text_library(),
        ),
    ));
    shader_files.push((
        shaders.join("GlyphuxColorCore.ush"),
        library(
            "GLYPHUX_COLOR_CORE",
            "glyphux's color glyph shading (color_core.wgsl). It declares color_tile, color_paint,\n// color_stop and color_recipe; the including shader defines them after it. They, and\n// every function calling them, take the tables texture first (a material's Custom node\n// can only pass textures as parameters)",
            &hlsl::color_library_with("Texture2D gx_tables"),
        ),
    ));
    shader_files.push((shaders.join("GlyphuxRecords.ush"), records_shader()));
    write_all(&shaders, &shader_files);

    write_all(&records, &[(records.join("GlyphuxRecords.h"), records_header())]);
    write_all(
        &shaders_public,
        &[(shaders_public.join("GlyphuxKernels.h"), kernels_header())],
    );
    write_all(
        &shaders_private,
        &[(shaders_private.join("GlyphuxKernels.cpp"), kernels_source(&kernels))],
    );
}

fn library(guard: &str, what: &str, body: &str) -> String {
    format!(
        "// {BANNER}\n// {what}.\n\n#ifndef {guard}\n#define {guard}\n\n{}\n#endif // {guard}\n",
        body.trim_end()
    )
}

fn kernels_header() -> String {
    let count = Kernel::ALL.len();
    let bindings = glyphux_gpu::Binding::ALL.len();
    let store = Kernel::ALL
        .iter()
        .position(|k| *k == Kernel::Store)
        .expect("the store kernel");
    format!(
        "// {BANNER}\n\n#pragma once\n\n#include \"CoreMinimal.h\"\n#include \"RenderGraphFwd.h\"\n\n\
/** glyphux-gpu's kernels, by their index in Kernel::ALL (what Rust passes), and their resources, by Binding index. */\n\
namespace GlyphuxKernels\n{{\n\
\tconstexpr int32 NumKernels = {count};\n\
\tconstexpr int32 NumBindings = {bindings};\n\
\t/** The kernel that writes the atlas pages. */\n\
\tconstexpr int32 Store = {store};\n\n\
\t/** What a batch binds: views of its buffers by Binding index, and the atlas pages. */\n\
\tstruct FBindings\n\t{{\n\t\tFRDGBufferSRVRef SRV[NumBindings] = {{}};\n\t\tFRDGBufferUAVRef UAV[NumBindings] = {{}};\n\t\tFRDGTextureUAVRef Atlas = nullptr;\n\t}};\n\n\
\t/** Whether a binding is written by the kernels (bound as a UAV). */\n\
\tGLYPHUXSHADERS_API bool IsOutput(int32 Binding);\n\n\
\t/** The binding's name, for debugging. */\n\
\tGLYPHUXSHADERS_API const TCHAR* BindingName(int32 Binding);\n\n\
\t/** Adds kernel Kernel's dispatch of Groups workgroups; false for an index that is not a kernel or a resource missing from Bindings. */\n\
\tGLYPHUXSHADERS_API bool AddPass(FRDGBuilder& GraphBuilder, int32 Kernel, const FBindings& Bindings, FIntVector Groups);\n}}\n"
    )
}

fn records_header() -> String {
    use records::{
        PASS_ALL, PASS_COLOR, QUAD_FLOATS, RECORD_TEXELS, RECORDS_PER_ROW, SURFACE_QUADS_PER_ROW, TABLES_WIDTH,
    };
    format!(
        "// Generated by the Glyphux plugin's rust/build.rs from rust/src/records.rs: do not edit.\n\n#pragma once\n\n#include \"CoreMinimal.h\"\n\n/** The sizes of what Rust gives C++ to draw (rust/src/records.rs and rust/src/draw.rs describe them). */\nnamespace GlyphuxRecords\n{{\n\t/** Texels (four floats) per monochrome glyph record, and records per row of the records texture. */\n\tconstexpr int32 RecordTexels = {RECORD_TEXELS};\n\tconstexpr int32 RecordsPerRow = {RECORDS_PER_ROW};\n\tconstexpr int32 RecordsWidth = RecordTexels * RecordsPerRow;\n\t/** Texels per row of the color tables texture. */\n\tconstexpr int32 TablesWidth = {TABLES_WIDTH};\n\t/** Floats per quad. */\n\tconstexpr int32 QuadFloats = {QUAD_FLOATS};\n\t/** Quads per row of a text surface's quads texture (three texels each). */\n\tconstexpr int32 SurfaceQuadsPerRow = {SURFACE_QUADS_PER_ROW};\n\t/** The pass of a monochrome glyph drawn alone (all its passes at once), and of color glyphs. */\n\tconstexpr int32 PassAll = {PASS_ALL};\n\tconstexpr int32 PassColor = {PASS_COLOR};\n}}\n"
    )
}

fn records_shader() -> String {
    use records::{
        PASS_ALL, PASS_COLOR, QUAD_FLOATS, RECORD_TEXELS, RECORDS_PER_ROW, SURFACE_QUADS_PER_ROW, TABLES_WIDTH,
    };
    format!(
        "// Generated by the Glyphux plugin's rust/build.rs from rust/src/records.rs: do not edit.\n// The layout of the glyph records and color tables textures.\n\n#ifndef GLYPHUX_RECORDS\n#define GLYPHUX_RECORDS\n\n#define GLYPHUX_RECORD_TEXELS {RECORD_TEXELS}\n#define GLYPHUX_RECORDS_PER_ROW {RECORDS_PER_ROW}\n#define GLYPHUX_TABLES_WIDTH {TABLES_WIDTH}\n#define GLYPHUX_QUAD_FLOATS {QUAD_FLOATS}\n#define GLYPHUX_SURFACE_QUADS_PER_ROW {SURFACE_QUADS_PER_ROW}\n#define GLYPHUX_PASS_ALL {PASS_ALL}\n#define GLYPHUX_PASS_COLOR {PASS_COLOR}\n\n#endif // GLYPHUX_RECORDS\n"
    )
}

fn shader_class(kernel: Kernel) -> String {
    format!("FGlyphuxKernel_{}", kernel.entry_point())
}

fn kernels_source(kernels: &[(Kernel, HlslKernel)]) -> String {
    let mut o = format!(
        "// {BANNER}\n\n#include \"Generated/GlyphuxKernels.h\"\n\n#include \"DataDrivenShaderPlatformInfo.h\"\n#include \"GlobalShader.h\"\n#include \"RenderGraphBuilder.h\"\n#include \"RenderGraphUtils.h\"\n#include \"ShaderParameterStruct.h\"\n"
    );
    for (kernel, k) in kernels {
        let class = shader_class(*kernel);
        let _ = writeln!(
            o,
            "\nclass {class} : public FGlobalShader\n{{\npublic:\n\tDECLARE_GLOBAL_SHADER({class});\n\tSHADER_USE_PARAMETER_STRUCT({class}, FGlobalShader);\n\n\tBEGIN_SHADER_PARAMETER_STRUCT(FParameters, )"
        );
        for b in &k.bindings {
            let line = match b.resource {
                HlslResource::Buffer => format!("SHADER_PARAMETER_RDG_BUFFER_SRV(ByteAddressBuffer, {})", b.name),
                HlslResource::RwBuffer => format!("SHADER_PARAMETER_RDG_BUFFER_UAV(RWByteAddressBuffer, {})", b.name),
                HlslResource::RwTextureArray => {
                    format!("SHADER_PARAMETER_RDG_TEXTURE_UAV(RWTexture2DArray<float4>, {})", b.name)
                }
            };
            let _ = writeln!(o, "\t\t{line}");
        }
        let _ = writeln!(
            o,
            "\tEND_SHADER_PARAMETER_STRUCT()\n\n\tstatic bool ShouldCompilePermutation(const FGlobalShaderPermutationParameters& Parameters)\n\t{{\n\t\treturn IsFeatureLevelSupported(Parameters.Platform, ERHIFeatureLevel::SM5);\n\t}}\n}};\n\nIMPLEMENT_GLOBAL_SHADER({class}, \"/Plugin/Glyphux/Private/Generated/{}.usf\", \"{}\", SF_Compute);",
            kernel.entry_point(),
            hlsl::ENTRY_POINT
        );
    }
    o.push_str("\nbool GlyphuxKernels::IsOutput(int32 Binding)\n{\n\tswitch (Binding)\n\t{\n");
    for b in glyphux_gpu::Binding::ALL {
        if !b.read_only() {
            let _ = writeln!(o, "\tcase {}: return true;", b.index());
        }
    }
    o.push_str("\tdefault: return false;\n\t}\n}\n");
    o.push_str("\nconst TCHAR* GlyphuxKernels::BindingName(int32 Binding)\n{\n\tswitch (Binding)\n\t{\n");
    for b in glyphux_gpu::Binding::ALL {
        let _ = writeln!(o, "\tcase {}: return TEXT(\"Glyphux.{b:?}\");", b.index());
    }
    o.push_str("\tdefault: return TEXT(\"Glyphux.Unknown\");\n\t}\n}\n");
    o.push_str("\nbool GlyphuxKernels::AddPass(FRDGBuilder& GraphBuilder, int32 Kernel, const FBindings& Bindings, FIntVector Groups)\n{\n\tswitch (Kernel)\n\t{\n");
    for (i, (kernel, k)) in kernels.iter().enumerate() {
        let class = shader_class(*kernel);
        let _ = writeln!(
            o,
            "\tcase {i}:\n\t{{\n\t\t{class}::FParameters* P = GraphBuilder.AllocParameters<{class}::FParameters>();"
        );
        let mut checks = Vec::new();
        for b in &k.bindings {
            let idx = b.binding.index();
            let value = match b.resource {
                HlslResource::Buffer => format!("Bindings.SRV[{idx}]"),
                HlslResource::RwBuffer => format!("Bindings.UAV[{idx}]"),
                HlslResource::RwTextureArray => "Bindings.Atlas".to_string(),
            };
            checks.push(format!("!{value}"));
            let _ = writeln!(o, "\t\tP->{} = {value};", b.name);
        }
        let _ = writeln!(
            o,
            "\t\tif ({})\n\t\t{{\n\t\t\treturn false;\n\t\t}}\n\t\tTShaderMapRef<{class}> Shader(GetGlobalShaderMap(GMaxRHIFeatureLevel));\n\t\tFComputeShaderUtils::AddPass(GraphBuilder, RDG_EVENT_NAME(\"Glyphux {}\"), Shader, P, Groups);\n\t\treturn true;\n\t}}",
            checks.join(" || "),
            kernel.entry_point()
        );
    }
    o.push_str("\tdefault:\n\t\treturn false;\n\t}\n}\n");
    o
}

/// Writes changed files and removes the others in `dir`.
fn write_all(dir: &Path, files: &[(PathBuf, String)]) {
    for (path, contents) in files {
        if std::fs::read(path).is_ok_and(|old| old == contents.as_bytes()) {
            continue;
        }
        std::fs::create_dir_all(path.parent().expect("a parent")).expect("create the generated folder");
        std::fs::write(path, contents).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
    }
    if let Ok(entries) = std::fs::read_dir(dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_file() && !files.iter().any(|(f, _)| *f == path) {
                let _ = std::fs::remove_file(&path);
            }
        }
    }
}
